"""Train the multigene mutation profile classifier (multinomial logistic regression).

Training data is synthesized from clinically grounded per-class gene mutation
marginals (NSCLC co-mutation literature patterns). Trained weights are exported
as a TypeScript module embedded in the app; inference runs in TypeScript.

Usage: python3 tools/train_ml_model.py
"""
import json
import os

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import train_test_split

OUT_PATH = os.path.join(os.path.dirname(__file__), "..", "src", "lib", "ml", "model-weights.ts")

GENES = ["egfr", "kras", "tp53", "alk", "stk11", "met"]

CLASSES = [
    "egfr_driven",
    "kras_driven",
    "kras_stk11",
    "alk_driven",
    "met_altered",
    "stk11_altered",
    "tp53_dominant",
    "complex_multidriver",
    "pan_negative",
]

# Per-class mutated probability per gene, order = GENES.
MARGINALS = {
    "egfr_driven":          [0.90, 0.01, 0.35, 0.01, 0.01, 0.01],
    "kras_driven":          [0.01, 0.86, 0.42, 0.01, 0.12, 0.01],
    "kras_stk11":           [0.01, 0.88, 0.38, 0.01, 0.88, 0.01],
    "alk_driven":           [0.01, 0.01, 0.30, 0.90, 0.01, 0.01],
    "met_altered":          [0.01, 0.01, 0.25, 0.01, 0.01, 0.88],
    "stk11_altered":        [0.01, 0.03, 0.20, 0.01, 0.90, 0.01],
    "tp53_dominant":        [0.01, 0.01, 0.94, 0.01, 0.01, 0.01],
    "complex_multidriver":  [0.55, 0.55, 0.50, 0.30, 0.25, 0.35],
    "pan_negative":         [0.02, 0.02, 0.03, 0.01, 0.02, 0.01],
}

UNKNOWN_RATE = 0.08  # testing coverage gaps


def features_from_statuses(statuses):
    """18 features: 6 mutated indicators, 6 unknown indicators, 6 pair terms."""
    mut = [1.0 if statuses[g] == "mutated" else 0.0 for g in GENES]
    unk = [1.0 if statuses[g] == "unknown" else 0.0 for g in GENES]
    pairs = [
        mut[1] * mut[4],  # KRAS x STK11
        mut[2] * mut[0],  # TP53 x EGFR
        mut[2] * mut[1],  # TP53 x KRAS
        mut[2] * mut[3],  # TP53 x ALK
        mut[2] * mut[5],  # TP53 x MET
        mut[4] * mut[5],  # STK11 x MET
    ]
    return np.array(mut + unk + pairs)


def sample(class_name, rng):
    statuses = {}
    for i, gene in enumerate(GENES):
        r = rng.random()
        if r < UNKNOWN_RATE:
            statuses[gene] = "unknown"
        elif r < UNKNOWN_RATE + MARGINALS[class_name][i]:
            statuses[gene] = "mutated"
        else:
            statuses[gene] = "wildtype"
    return statuses


def main():
    rng = np.random.default_rng(42)
    X, y = [], []
    for ci, cls in enumerate(CLASSES):
        for _ in range(900):
            X.append(features_from_statuses(sample(cls, rng)))
            y.append(ci)
    X = np.array(X)
    y = np.array(y)

    X_tr, X_te, y_tr, y_te = train_test_split(X, y, test_size=0.2, random_state=7, stratify=y)
    clf = LogisticRegression(max_iter=5000, C=2.0)
    clf.fit(X_tr, y_tr)
    acc = clf.score(X_te, y_te)
    print(f"holdout accuracy: {acc:.4f}")

    weights = {
        "version": 1,
        "genes": GENES,
        "classes": CLASSES,
        "features": ["mut_" + g for g in GENES]
        + ["unk_" + g for g in GENES]
        + ["pair_kras_stk11", "pair_tp53_egfr", "pair_tp53_kras", "pair_tp53_alk", "pair_tp53_met", "pair_stk11_met"],
        "coefficients": clf.coef_.round(5).tolist(),
        "intercepts": clf.intercept_.round(5).tolist(),
        "holdout_accuracy": round(float(acc), 4),
    }

    ts = (
        "// Auto-generated by tools/train_ml_model.py — do not edit by hand.\n"
        "// Trained on synthesized data from clinically grounded NSCLC co-mutation marginals.\n"
        "export const MODEL_WEIGHTS = " + json.dumps(weights, indent=1) + " as const;\n"
    )
    with open(OUT_PATH, "w") as f:
        f.write(ts)
    print("wrote", os.path.normpath(OUT_PATH))


if __name__ == "__main__":
    main()
